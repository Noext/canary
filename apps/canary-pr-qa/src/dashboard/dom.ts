/** A missing control fails explicitly; IDs and element-specific APIs are checked by tsc. */
export function $<K extends keyof Elements>(id: K): Elements[K] {
  const node = document.getElementById(id);
  if (!node) {
    throw new Error(`Dashboard control missing: ${id}`);
  }
  return node as Elements[K];
}
